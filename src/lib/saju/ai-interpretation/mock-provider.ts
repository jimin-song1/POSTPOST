function sectionExtras(row:Row,value:DomainProfile){
  if(!value.extra)return[] as string[];
  const topic=row.topic??row.title,domain=domainOf(row.evidenceGroup??"");
  const keep=domain==="IDENTITY"?/겉과 속이 다르게|한 문장으로 보는 나/.test(topic):
    domain==="WORK"?/배우고 시험|배움/.test(topic):
    domain==="WEALTH"?/돈 때문에 생기는 인간관계/.test(topic):
    domain==="RELATIONSHIP"?/좋아할 때 표현/.test(topic):false;
  return keep?value.extra:[];
}
function buildParagraphs(row:Row,index:number){
  const value=profile(row,index),topic=row.topic??row.title,angle=editorialAngle(row,index),domain=domainOf(row.evidenceGroup??"");
  const group=row.evidenceGroup??"";
  const paragraphs=[
    angle.scene,
    joinUpsideShadow(value.strength,value.shadow),
    withoutTopicPrefix(angle.consequence,topic)
  ];

  if(["IDENTITY","WORK","WEALTH","RELATIONSHIP","WELLNESS","SAMJAE","DAEUN"].includes(domain)){
    const consequence=withoutTopicPrefix(value.consequence,topic);
    if(consequence&&consequence!==paragraphs[2])paragraphs.push(consequence);
  }

  if(["CORE","PILLARS","HIDDEN_STEMS","STRUCTURE_USEFUL"].includes(group)){
    paragraphs.push(value.scene);
  }

  if(["IDENTITY","ELEMENTS","STRENGTH"].includes(group)){
    paragraphs.push(
      value.scene,
      value.action,
      value.extra?.[0]??""
    );
  }

  if(["WORK","WEALTH","RELATIONSHIP"].includes(group)){
    paragraphs.push(
      value.scene,
      value.action
    );
  }

  if(value.timing&&shouldIncludeTimingNote(row))paragraphs.push(value.timing);

  const coreExpansion=coreChapterExpansion(row);if(coreExpansion.length)paragraphs.push(...coreExpansion);
  const depthExpansion=chapterDepthExpansion(row,index);if(depthExpansion.length)paragraphs.push(...depthExpansion);
  const extras=sectionExtras(row,value);if(extras.length)paragraphs.push(...extras);

  return paragraphs
    .map(paragraph=>naturalizeNarration(paragraph.trim()))
    .filter(Boolean)
    .filter((paragraph,paragraphIndex,rows)=>rows.indexOf(paragraph)===paragraphIndex);
}

function report(input:InterpretationInput):StructuredInterpretation{
  const rows=input.reportPlan??[];
  const sections=rows.map((row,index)=>{
    const ids=evidenceFor(row,row.pageNumber??index),value=profile(row,index),angle=editorialAngle(row,index);
    const fullParagraphs=buildParagraphs(row,index);
    const frontMatterParagraphs=[
      fullParagraphs[0],
      fullParagraphs[1],
      fullParagraphs[3]??fullParagraphs[2]
    ].filter((paragraph):paragraph is string=>typeof paragraph==="string"&&paragraph.length>0);
    const paragraphs=row.contentKind==="FRONT_MATTER"
      ?frontMatterParagraphs
      :row.contentKind==="PROFESSIONAL"
        ?[value.scene,value.consequence,value.action]
        :fullParagraphs;
    const pageNo=row.pageNumber??index+1;
    return {
      id:row.id,
      chapterNumber:row.chapterNumber,
      title:row.title,
      headline:row.title,
      lead:naturalizeNarration(value.lead),
      body:paragraphs.join("\n\n"),
      paragraphs,
      keyPoints:[naturalizeNarration(angle.action)],
      evidenceIds:ids,
      partNumber:row.partNumber,
      partTitle:row.partTitle,
      evidenceGroup:row.evidenceGroup,
      contentKind:row.contentKind,
      noveltyElements:["NEW_CLAIM","NEW_SCENE","NEW_UPSIDE","NEW_SHADOW","NEW_ACTION"],
      claimsUsed:[`PAGE-${pageNo}-${row.id}`],
      scenesUsed:[`SCENE-${row.id}`],
      priorSectionSummary:index?"앞 section의 결론을 반복하지 않고 현재 주제의 결과만 이어갑니다.":"",
      domainConsequence:`${row.id}에서만 다루는 ${row.topic??row.title}의 생활 결과입니다.`,
      ...(row.contentKind==="PROFESSIONAL"?{professionalDetails:{summary:"고객용 해설에 사용한 계산 근거를 이곳에서만 확인합니다.",evidenceIds:ids}}:{})
    };
  });
  return {
    status:"completed",
    reportType:input.reportType,
    headline:"계산은 그대로 두고, 삶의 장면으로 풀었습니다",
    summary:"한 가지 표지만으로 단정하지 않고 서로 관련된 근거가 실제 선택과 행동에서 어떻게 이어지는지 살폈습니다.",
    sections,
    highlights:["같은 성향도 일, 돈, 관계에서는 서로 다른 행동으로 나타납니다."],
    cautions:["움직임이 크다는 말과 유리하다는 말은 같은 뜻이 아닙니다."],
    timeline:[],
    disclaimer:"전통 명리 이론을 바탕으로 한 참고 콘텐츠이며 중요한 결정을 대신하지 않습니다."
  };
}

