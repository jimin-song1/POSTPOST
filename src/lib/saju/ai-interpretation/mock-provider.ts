function withoutTopicPrefix(text:string,topic:string){
  if(!text.startsWith(topic))return text;
  return text.slice(topic.length).replace(/^(?:에서는|은|는|이|가|을|를|과|와)?[,·:\s]*/,"").trim();
}
function trimOpening(text:string){
  return text
    .replace(/^잘 쓰이면\s*/,"")
    .replace(/^다만\s*/,"")
    .replace(/^반대로\s*/,"")
    .replace(/^특히\s*/,"")
    .trim();
}
function joinUpsideShadow(strength:string,shadow:string){
  const upside=trimOpening(strength),downside=trimOpening(shadow);
  return `${upside} 다만 이 힘이 한쪽으로 쏠리면 ${downside.charAt(0).toLowerCase()+downside.slice(1)}`;
}
function naturalizeNarration(text:string){
  return text
    .replaceAll("실제 생활에서는","생활에서는")
    .replaceAll("실제 생활에서","생활에서")
    .replaceAll("중심으로 봅니다.","부터 보는 편이에요.")
    .replaceAll("살펴봅니다.","살펴보는 편이에요.")
    .replaceAll("도움이 됩니다.","도움이 돼요.")
    .replaceAll("도움이 될 수 있습니다.","도움이 될 수 있어요.")
    .replaceAll("중요합니다.","중요해요.")
    .replaceAll("필요합니다.","필요해요.")
    .replaceAll("좋습니다.","좋아요.")
    .replaceAll("편이 좋습니다.","편이 좋아요.")
    .replaceAll("수 있습니다.","수 있어요.")
    .replaceAll("않습니다.","않아요.")
    .replaceAll("됩니다.","돼요.")
    .replaceAll("입니다.","이에요.")
    .replaceAll("있습니다.","있어요.");
}

